async function seed() {
  try {
    await mongoose.connect(MONGODB_URI);
    console.log("Connected to MongoDB");

    // Seed Domain TLDs
    await DomainTLD.deleteMany({});
    console.log("Cleared existing domain TLDs");

    const tldDocs = domainTLDs.map((tld, index) => {
      const margin = isCCTLD(tld.tld) ? MARGIN_CCTLD : MARGIN_GENERIC;
      return {
        tld: tld.tld,
        provider: "resellerspanel",
        registrationPrice: tld.registrationPrice,
        renewalPrice: tld.renewalPrice,
        transferPrice: tld.registrationPrice,
        currency: "USD",
        margin,
        finalPrice: applyMargin(tld.registrationPrice, margin),
        finalRenewalPrice: applyMargin(tld.renewalPrice, margin),
        description: tld.description,
        features: [],
        isActive: true,
        isPromo: tld.isPromo || false,
        promoPrice: tld.isPromo ? tld.registrationPrice : undefined,
        promoDuration: tld.promoDuration,
        category: tld.category,
        sortOrder: index + 1,
      };
    });

    await DomainTLD.insertMany(tldDocs);
    console.log(`Seeded ${tldDocs.length} domain TLDs`);

    // Seed Hosting Plans
    await HostingPlan.deleteMany({});
    console.log("Cleared existing hosting plans");

    const planDocs = hostingPlans.map((plan) => ({
      ...plan,
      finalPrice: applyMargin(plan.price, 15),
      finalRenewalPrice: applyMargin(plan.renewalPrice, 15),
    }));

    await HostingPlan.insertMany(planDocs);
    console.log(`Seeded ${planDocs.length} hosting plans`);

    console.log("Seed completed successfully");
    process.exit(0);
  } catch (error) {
    console.error("Seed failed:", error);
    process.exit(1);
  }
}

seed();
