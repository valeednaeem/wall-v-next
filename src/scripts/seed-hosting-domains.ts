function applyMargin(price: number, margin: number): number {
  return Math.round(price * (1 + margin / 100) * 100) / 100;
}

function isCCTLD(tld: string): boolean {
  const ccTLDs = [
    "uk", "co.uk", "me.uk", "org.uk",
    "eu", "de", "fr", "it", "es", "nl", "be", "at", "ch", "se", "no", "fi", "dk", "pt", "pl", "gr", "ie",
    "us", "ca", "com.au", "net.au", "org.au", "co.nz", "net.nz", "org.nz",
    "com.cn", "net.cn", "org.cn", "com.tw", "net.tw", "com.hk",
    "co.jp", "co.in", "co.za", "com.mx", "com.br", "com.sg",
    "tv", "cc", "ws", "asia",
  ];
  return ccTLDs.includes(tld);
}

